type BlueprintResource struct{ client *client.Client }
type blueprintModel struct {
	ID               types.String `tfsdk:"id"`
	Name             types.String `tfsdk:"name"`
	Type             types.String `tfsdk:"type"`
	Description      types.String `tfsdk:"description"`
	Color            types.String `tfsdk:"color"`
	Icon             types.String `tfsdk:"icon"`
	EnrollmentActive types.Bool   `tfsdk:"enrollment_active"`
	EnrollmentCode   types.String `tfsdk:"enrollment_code"`
	SourceType       types.String `tfsdk:"source_type"`
	SourceID         types.String `tfsdk:"source_id"`
}

var (
	_ resource.Resource                   = &BlueprintResource{}
	_ resource.ResourceWithConfigure      = &BlueprintResource{}
	_ resource.ResourceWithImportState    = &BlueprintResource{}
	_ resource.ResourceWithValidateConfig = &BlueprintResource{}
	_ resource.ResourceWithModifyPlan     = &BlueprintResource{}
)

func NewBlueprintResource() resource.Resource { return &BlueprintResource{} }
func (*BlueprintResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_blueprint"
}
